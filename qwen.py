import os
from openai import OpenAI

# Настройка клиента
client = OpenAI(
    base_url="http://127.0.0.1:1234/v1", 
    api_key="lm-studio"
)

input_file = "raw_text.txt"
output_file = "result.tex" # Сохраняем сразу как .tex файл

# Шаблон LaTeX документа с поддержкой русского языка
latex_template_start = r"""
\documentclass[12pt, a4paper]{article}
\usepackage[utf8]{inputenc}
\usepackage[T2A]{fontenc}
\usepackage[left=2cm, right=2cm, top=2cm, bottom=2cm]{geometry}

\begin{document}

"""

latex_template_end = r"""
\end{document}
"""

if not os.path.exists(input_file):
    print(f"Ошибка: Файл {input_file} не найден.")
    exit()

print(f"Чтение файла {input_file}...")
with open(input_file, "r", encoding="utf-8") as f:
    raw_text = f.read()

# Промпт (оставляем тот же, он сработал хорошо)
system_instruction = """
Ты — специализированный ИИ-транслятор математической речи в строгий LaTeX. 
Твоя задача — превратить расшифровку в научную запись, используя символьную логику везде, где это уместно.

### ГЛАВНЫЙ ПРИНЦИП:
1. Исходная структура предложений сохраняется.
2. ЗАПРЕЩЕНО использовать слова там, где есть общепринятый математический символ.

### ОБЯЗАТЕЛЬНАЯ СИМВОЛИЗАЦИЯ (ЖЕСТКО):
Ты ОБЯЗАН заменять следующие словесные конструкции на символы LaTeX:
— "для любого", "для каждого", "для всех", "при любом" → $\forall$
— "существует", "найдется", "существуют" → $\exists$
— "такой что", "выполняется", "что выполняется" → $:$ (двоеточие) или $|$
— "принадлежит", "из множества", "лежит в" → $\in$
— "не принадлежит" → $\notin$
— "следовательно", "отсюда следует", "значит" → $\Rightarrow$
— "тогда и только тогда", "эквивалентно" → $\Leftrightarrow$
— "стремится к" → $\to$
— "бесконечность" → $\infty$

### ГРЕЧЕСКИЕ БУКВЫ И ОБОЗНАЧЕНИЯ:
— Любое название греческой буквы (альфа, бета, гамма, дельта, эпсилон и т.д.) → соответствующий символ ($\alpha, \beta, \gamma, \delta, \epsilon$).
— Описательные выражения типа "гамма от т" или "икс от тэ" всегда записывай как $\gamma(t)$ и $x(t)$.

### ТРЕБОВАНИЯ К ОФОРМЛЕНИЮ:
1. Математические утверждения (кванторы + переменные) должны объединяться в единые логические блоки.
   *Пример:* "для любого икс из эр" → $\forall x \in \mathbb{R}$.
2. Инлайн-формулы: используй $...$ для коротких выражений.
3. Выключные формулы: используй \[ ... \] ТОЛЬКО для определений или длинных равенств.
4. Текст между формулами (союзы, вводные слова "Рассмотрим", "Пусть", "Тогда") оставляй на русском языке без изменений.

### ПРИМЕР ТРАНСФОРМАЦИИ:
Исходник: "Для любого эпсилон больше нуля существует дельта больше нуля такая что для любого икс если икс минус икс ноль меньше дельта то эф от икс минус эф от икс ноль меньше эпсилон"
Результат: $\forall \epsilon > 0 \ \exists \delta > 0 : \forall x \ |x - x_0| < \delta \Rightarrow |f(x) - f(x_0)| < \epsilon$

### ВЫХОДНЫЕ ДАННЫЕ:
Выдай только обработанный текст. Никаких комментариев от себя.
"""

print("Обработка текста нейросетью...")

try:
    completion = client.chat.completions.create(
        model="qwen2.5-7b-instruct-1m",
        messages=[
            {"role": "system", "content": system_instruction},
            {"role": "user", "content": raw_text}
        ],
        temperature=0.2,
    )

    content_body = completion.choices[0].message.content

    # Склеиваем шаблон + текст от нейросети + конец шаблона
    full_latex_document = latex_template_start + content_body + latex_template_end

    print("Сохранение результата...")
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(full_latex_document)

    print(f"\nГОТОВО! Файл сохранен как: {output_file}")
    print("Теперь вы можете открыть этот файл в TeXStudio, Overleaf или любом другом редакторе и скомпилировать.")

except Exception as e:
    print(f"Ошибка: {e}")
